import 'dart:typed_data';
import '../lib/core/hg_reg.dart';

void main() {
  final key = Uint8List.fromList([
    0x2b,0x7e,0x15,0x16,0x28,0xae,0xd2,0xa6,0xab,0xf7,0x15,0x88,0x09,0xcf,0x4f,0x3c
  ]);
  final iv = Uint8List.fromList([
    0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f
  ]);
  final pt = Uint8List.fromList([
    0x6b,0xc1,0xbe,0xe2,0x2e,0x40,0x9f,0x96,0xe9,0x3d,0x7e,0x11,0x73,0x93,0x17,0x2a
  ]);
  final ct = HgReg.aesCbcEncryptNoPad(key, iv, pt);
  final hex = ct.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
  const want = '7649abac8119b246cee98e9b12e9197d';
  print('got  ' + hex);
  print('want ' + want);
  print(hex == want ? 'AES OK' : 'AES FAIL');
  final body = HgReg.buildPayload('11111111-2222-3333-4444-555555555555', 1700000000000);
  print('payload len ' + body.length.toString() + ' head ' + body.sublist(0, 6).toString());
}
